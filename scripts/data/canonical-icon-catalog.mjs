export function canonicalEquipmentIcon(name, bonus=0, category="") {
  const file = CANONICAL_EQUIPMENT_ICONS[String(name ?? "").trim().toLowerCase()];
  if (!file) return null; // Non-SRD/custom items retain the source icon.
  const rank = Math.trunc(Number(bonus) || 0);
  if (rank < 0 || rank > 3) return null;
  // +3 armor is Legendary in D&D5e; every other +3 equipment group is Very Rare.
  const frame = rank === 3 && category === "armor" ? "legendary" : String(rank);
  return `${ROOT}/equipment-variants/${file.slice(0, -5)}__${frame}.webp`;
}

// Deterministic, presentation-only v0.6.0 upgrade condition.
// Existing customized artwork stored outside the prior bundled/native icon roots remains untouched.
export function isLegacyCatalogArt(path) {
  const value = String(path ?? "").trim();
  return !value || value === "icons/containers/bags/coinpouch-simple-leather-silver-brown.webp"
    || value.startsWith("icons/")
    || value.startsWith("systems/dnd5e/")
    || value.startsWith("modules/dnd5e-crafting-core/icons/");
}
